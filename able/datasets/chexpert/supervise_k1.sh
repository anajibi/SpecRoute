#!/bin/bash
# Unattended supervisor for the CheXpert k=1 run. Authorised by the user 2026-11-08:
# restart from the newest verified checkpoint up to 3 times on a crash, and on a
# NON-FINITE loss recover once at half the learning rate, then stop and report.
#
# Why a supervisor rather than a bare `while` loop around the trainer:
#
#  * SUCCESS AND CRASH LOOK THE SAME from the outside -- both are "the process exited".
#    The only trustworthy end-of-run marker is global_step reaching max_steps, so that is
#    what is checked, not the exit code.
#
#  * A TRUE RESUME IGNORES THE CONFIG'S lr. Lightning restores optimizer param_groups from
#    the checkpoint, so editing lr in the yaml and resuming would run the OLD lr while the
#    log claimed the new one -- the kind of silent divergence this project keeps getting
#    bitten by. The half-lr recovery therefore uses init_from into a FRESH output dir, which
#    builds a new optimiser at the new lr and still carries the EMA across, instead of
#    pretending a resume can change it.
#
#  * A NON-FINITE CHECKPOINT MUST NOT BE RESUMED FROM. Anything written at or after the
#    blow-up is quarantined rather than deleted, so the failure stays inspectable.
set -u
R=/home/exouser/SpecRoute
CFG=$R/experiments/hdae/configs/chexpert256_k1.yaml
OUT=$R/experiments/hdae/outputs/chexpert256_k1
LOG=$OUT.log
SUP=$R/experiments/hdae/outputs/chexpert256_k1_supervisor.log
PY=$R/.venv/bin/python
MAX_STEPS=15625
CRASH_BUDGET=3
NONFINITE_BUDGET=1
crashes=0; nonfinite=0

say () { echo "[$(date -u +%FT%TZ)] $*" | tee -a "$SUP"; }

newest_step () {   # highest global_step reached, 0 if unknown
  # Filenames alone are NOT enough. The janitor now prunes every verified epoch=*.ckpt to
  # keep the disk alive, so the only local checkpoint left can be last.ckpt -- which carries
  # no step in its name. Reading the name only would report 0 on a COMPLETED run and the
  # supervisor would restart it. So: try the names, then fall back to the step stored inside
  # last.ckpt, then to s3, which holds every checkpoint ever written.
  local n
  n=$(ls -1 "$OUT"/checkpoints/epoch=*.ckpt 2>/dev/null \
      | grep -oE 'step=[0-9]+' | grep -oE '[0-9]+' | sort -n | tail -1)
  if [ -z "${n:-}" ] && [ -f "$OUT/checkpoints/last.ckpt" ]; then
    n=$("$PY" -c "
import torch,sys
try:
    print(int(torch.load(sys.argv[1], map_location='cpu', weights_only=False).get('global_step', 0)))
except Exception:
    print(0)
" "$OUT/checkpoints/last.ckpt" 2>/dev/null)
  fi
  if [ -z "${n:-}" ] || [ "${n:-0}" = "0" ]; then
    n=$(aws s3 ls "s3://najibi-research-7f2a/able/chexpert/v2/hdae/k1/" 2>/dev/null \
        | grep -oE 'step=[0-9]+' | grep -oE '[0-9]+' | sort -n | tail -1)
  fi
  echo "${n:-0}"
}

nonfinite_in_log () {
  tail -c 60000 "$LOG" 2>/dev/null | tr '\r' '\n' \
    | grep -qiE "loss=nan|loss=inf|non-finite|Expected.*finite"
}

say "supervisor up: budget ${CRASH_BUDGET} crash restarts, ${NONFINITE_BUDGET} half-lr recovery"

while true; do
  # wait for the current trainer to leave the field
  while pgrep -f "configs/chexpert256_k1" >/dev/null; do sleep 60; done
  step=$(newest_step); step=${step:-0}
  say "trainer exited at step ${step}/${MAX_STEPS}"

  if [ "$step" -ge "$MAX_STEPS" ]; then
    say "DONE: reached max_steps"
    exit 0
  fi

  if nonfinite_in_log; then
    if [ "$nonfinite" -ge "$NONFINITE_BUDGET" ]; then
      say "STOP: non-finite a second time; not halving again. Needs a human."
      exit 1
    fi
    nonfinite=$((nonfinite+1))
    QUAR=$OUT/quarantine_nonfinite
    mkdir -p "$QUAR"
    # keep the newest checkpoint for inspection but do not resume from it
    newest=$(ls -1t "$OUT"/checkpoints/epoch=*.ckpt 2>/dev/null | head -1)
    [ -n "${newest:-}" ] && { cp -f "$newest" "$QUAR"/ 2>/dev/null; say "quarantined copy of $(basename "$newest")"; }
    good=$(ls -1t "$OUT"/checkpoints/epoch=*.ckpt 2>/dev/null | sed -n 2p)
    [ -z "${good:-}" ] && good="$newest"
    if [ -z "${good:-}" ]; then say "STOP: non-finite with no checkpoint to fall back to."; exit 1; fi
    NEWCFG=$R/experiments/hdae/configs/chexpert256_k1_lrhalf.yaml
    "$PY" - "$CFG" "$NEWCFG" "$good" <<'PYEOF'
import sys, re
src, dst, good = sys.argv[1:4]
s = open(src).read()
s = s.replace("  lr: 1.0e-4", "  lr: 5.0e-5")
s = re.sub(r'^  init_from: .*$', f'  init_from: "{good}"', s, flags=re.M)
s = s.replace("output_dir: experiments/hdae/outputs/chexpert256_k1",
              "output_dir: experiments/hdae/outputs/chexpert256_k1_lrhalf")
s = ("# AUTO-GENERATED by supervise_k1.sh after a non-finite loss. lr halved to 5e-5 and\n"
     "# init_from points at the last good checkpoint: a true RESUME would restore the old\n"
     "# optimizer param_groups and silently keep running at 1e-4.\n") + s
open(dst, "w").write(s)
PYEOF
    say "non-finite: recovering from $(basename "$good") at lr 5e-5 -> chexpert256_k1_lrhalf"
    cd "$R" && nohup setsid "$PY" experiments/hdae/scripts/train.py --config "$NEWCFG" \
      > "$R/experiments/hdae/outputs/chexpert256_k1_lrhalf.log" 2>&1 &
    CFG=$NEWCFG
    OUT=$R/experiments/hdae/outputs/chexpert256_k1_lrhalf
    LOG=$OUT.log
    sleep 120
    continue
  fi

  if [ "$crashes" -ge "$CRASH_BUDGET" ]; then
    say "STOP: ${crashes} restarts used and still not finished. Needs a human."
    exit 1
  fi
  crashes=$((crashes+1))
  say "crash restart ${crashes}/${CRASH_BUDGET} -- train.py resumes from the newest checkpoint by global_step"
  cd "$R" && nohup setsid "$PY" experiments/hdae/scripts/train.py --config "$CFG" >> "$LOG" 2>&1 &
  sleep 120
done
